/* ── STORY DECK + 图表懒加载 ─────────────────────────────────── */
(function(){
  const panelIds = ['ch1','ch2','ch3','ch4','ch5','epilogue'];
  const panels   = panelIds.map(id=>document.getElementById(id)).filter(Boolean);
  const tabs     = document.querySelectorAll('.story-tab');
  const navLinks = document.querySelectorAll('.nav-links a');
  const progress = document.querySelector('.story-progress-bar');
  const controls = document.querySelectorAll('.deck-button');

  // 每个章节对应的图表初始化函数
  const chartMap = {
    ch1: ()=>{ initCh1Chart(); },
    ch2: ()=>{ initCh2aChart(); initCh2bChart(); },
    ch3: ()=>{ initCh3aChart(); initCh3bChart(); },
    ch4: ()=>{ initCh4Charts(); },
    ch5: ()=>{ initCh5Chart(); },
  };

  let activeIdx = 0;

  function syncDeck(idx, scroll=false) {
    activeIdx = Math.max(0, Math.min(idx, panels.length-1));
    const activeId = panelIds[activeIdx];

    panels.forEach((p,i)=>{
      const on = i===activeIdx;
      p.classList.toggle('active', on);
      p.setAttribute('aria-hidden', String(!on));
      if (on) {
        p.querySelectorAll('.fade-in').forEach(el=>el.classList.add('visible'));
        if (chartMap[activeId]) setTimeout(()=>chartMap[activeId](), 60);
      }
    });

    tabs.forEach(t=>{ const on=t.dataset.target===activeId; t.classList.toggle('active',on); t.setAttribute('aria-selected',String(on)); });
    navLinks.forEach(l=>l.classList.toggle('active', l.getAttribute('href')==='#'+activeId));
    controls.forEach(b=>{ const step=Number(b.dataset.step||0); b.disabled=(activeIdx===0&&step<0)||(activeIdx===panels.length-1&&step>0); });
    if (progress) progress.style.width = `${((activeIdx+1)/panels.length)*100}%`;
    if (scroll) document.querySelector('.story-deck')?.scrollIntoView({behavior:'smooth',block:'start'});
  }

  tabs.forEach((t,i)=>t.addEventListener('click',()=>syncDeck(i, true)));
  controls.forEach(b=>b.addEventListener('click',()=>syncDeck(activeIdx+Number(b.dataset.step||0), true)));

  navLinks.forEach(l=>{
    l.addEventListener('click',e=>{
      const target = l.getAttribute('href')?.replace('#','');
      const idx = panelIds.indexOf(target);
      if (idx>=0) { e.preventDefault(); syncDeck(idx, true); }
    });
  });

  window.addEventListener('hashchange',()=>{
    const idx = panelIds.indexOf(location.hash.replace('#',''));
    if (idx>=0) syncDeck(idx,false);
  });

  syncDeck(0, false);
})();


