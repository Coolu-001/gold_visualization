/* ── 实时金价 ─────────────────────────────────────────────────── */
(function(){
  const priceEl = document.querySelector('.hero-price-value');
  const noteEl  = document.querySelector('.hero-price-note');
  if (!priceEl || !noteEl) return;
  const fallback = priceEl.textContent.trim();
  const pfmt = new Intl.NumberFormat('en-US',{minimumFractionDigits:2,maximumFractionDigits:2});
  const tfmt = new Intl.DateTimeFormat('zh-CN',{month:'2-digit',day:'2-digit',hour:'2-digit',minute:'2-digit',hour12:false});
  async function load() {
    try {
      const r = await fetch('https://api.gold-api.com/price/XAU',{cache:'no-store'});
      if (!r.ok) throw new Error(r.status);
      const q = await r.json();
      const price = Number(q.price ?? q.ask ?? q.bid);
      if (!isFinite(price)) throw new Error('no price');
      const ts = q.updatedAt ?? q.updated_at ?? q.timestamp;
      const d = ts ? new Date(typeof ts==='number'&&ts<1e12?ts*1000:ts) : new Date();
      priceEl.textContent = pfmt.format(price);
      noteEl.textContent  = `${tfmt.format(d)} 更新 · USD/oz`;
    } catch {
      priceEl.textContent = fallback;
      noteEl.textContent  = '实时价格获取失败 · 显示历史末值';
    }
  }
  load();
  setInterval(load, 5*60*1000);
})();

